export function getBrandLogoUrl(
  merchantName?: string | null,
  rawLabel?: string | null,
  logoUrl?: string | null,
  domain?: string | null
): string | null {
  // 0. Explicitly disabled or removed by user
  if (logoUrl === "none" || logoUrl === "disabled") {
    return null
  }

  // 1. Direct explicit logo URL if already available from backend or enrichment
  if (logoUrl && logoUrl.trim() !== "" && logoUrl.startsWith("http")) {
    return logoUrl.trim()
  }

  // 2. Direct domain if provided
  if (domain && domain.trim() !== "") {
    return `https://www.google.com/s2/favicons?domain=${domain.trim()}&sz=128`
  }

  if (!merchantName && !rawLabel) return null

  const target = `${merchantName || ""} ${rawLabel || ""}`
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "") // remove accents

  for (const [brand, brandDomain] of Object.entries(MAJOR_BRANDS)) {
    const brandClean = brand.normalize("NFD").replace(/[\u0300-\u036f]/g, "")
    // Match word boundaries or substring
    if (target.includes(brandClean)) {
      return `https://www.google.com/s2/favicons?domain=${brandDomain}&sz=128`
    }
  }

  return null
}
